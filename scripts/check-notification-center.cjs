/** Exercises the real shell, notification store and Radix UI with isolated backend/identity boundaries. */
const fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path'), http = require('node:http'), assert = require('node:assert/strict')
const { chromium, webkit } = require('playwright')
const { build } = require('./check-floating-header.cjs')
const repo = path.resolve(__dirname, '..')
async function check() {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'outclass-notification-center-'))
  let server, browser
  try {
    await build(root, { realNotificationState: true })
    server = http.createServer(async (request, response) => {
      const resource = new URL(request.url, 'http://localhost').pathname
      if (resource === '/api/platform/eligibility') { response.setHeader('Content-Type', 'application/json'); response.end('{"eligible":false}'); return }
      const file = ['/bundle.js', '/styles.css'].includes(resource) ? path.join(root, resource.slice(1)) : resource.startsWith('/assets/media/') ? path.join(repo, '.next/static/media', path.basename(resource)) : path.join(repo, 'public', resource)
      try { const data = await fs.readFile(file); response.setHeader('Content-Type', resource.endsWith('.js') ? 'text/javascript' : resource.endsWith('.css') ? 'text/css' : resource.endsWith('.svg') ? 'image/svg+xml' : resource.endsWith('.woff2') ? 'font/woff2' : 'image/jpeg'); response.end(data) }
      catch { response.setHeader('Content-Type', 'text/html; charset=utf-8'); response.end('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="/styles.css"></head><body><div id="root"></div><script src="/bundle.js"></script></body></html>') }
    })
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
    const base = `http://127.0.0.1:${server.address().port}`, startURL = `${base}/club/fixture-mii/workspace?section=overview&role=owner&notificationsFixture=1`
    const engine = process.env.OUTCLASS_NAV_BROWSER === 'webkit' ? webkit : chromium
    browser = await engine.launch({ headless: true, ...(engine === chromium ? { channel: 'chrome' } : {}) })
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } }), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => {
      window.fixtureStreams = []
      window.EventSource = class extends EventTarget { constructor(url) { super(); this.url = url; window.fixtureStreams.push(this) } close() { this.closed = true } }
    })
    await page.goto(startURL, { waitUntil: 'networkidle' })
    const bell = page.locator('[data-tour="notifications"]'), panel = page.getByRole('dialog', { name: 'Notifications', exact: true })
    const rows = panel.locator('.oc-notification-items > li')
    const open = async () => { const rect = await bell.boundingBox(); await page.mouse.click(rect.x + rect.width / 2, rect.y + rect.height / 2); await panel.waitFor({ state: 'visible' }); await page.waitForFunction(() => getComputedStyle(document.querySelector('.oc-notification-panel')).opacity === '1') }
    const close = async () => { await page.keyboard.press('Escape'); await panel.waitFor({ state: 'hidden' }) }
    const waitRead = id => page.waitForFunction(id => document.querySelector(`[data-notification-id="durable-${id}"]`)?.dataset.unread === 'false', id)
    const readCalls = () => page.evaluate(() => window.fixtureNotificationCalls.filter(call => call.action === 'read').length)
    await page.evaluate(() => scrollTo(0, 450))
    const originalScroll = await page.evaluate(() => scrollY), initialReads = await readCalls()
    await open()
    assert.equal(page.url(), startURL); assert.equal(await page.evaluate(() => scrollY), originalScroll)
    assert.equal(await readCalls(), initialReads)
    assert.equal(await bell.getAttribute('aria-expanded'), 'true'); assert.ok(await bell.getAttribute('aria-controls'))
    assert.equal(await rows.count(), 50)
    await bell.click(); await panel.waitFor({ state: 'hidden' })
    await bell.evaluate(el => el.focus({ preventScroll: true })); await page.keyboard.press('Enter'); await panel.waitFor(); await page.waitForFunction(() => document.activeElement?.classList.contains('oc-notification-panel')); await page.keyboard.press('Tab')
    assert.equal(await panel.getByRole('button', { name: 'Mark all updates as read' }).evaluate(el => el === document.activeElement), true)
    await close(); assert.equal(await bell.evaluate(el => el === document.activeElement), true)
    await open(); await page.getByRole('heading', { name: 'Overview', exact: true }).click(); await panel.waitFor({ state: 'hidden' })
    console.log('PASS bell toggle, outside/Escape dismissal and no navigation, scrolling or automatic reads')
    await page.evaluate(() => scrollTo(0, 0)); await open()
    await page.screenshot({ path: '/tmp/outclass-notification-center-desktop.png' })
    if (process.argv.includes('--serve')) { console.log('Isolated notification fixture', base); await new Promise(() => {}); return }
    await panel.getByRole('button', { name: /^Welcome to recruitment/ }).click()
    await panel.getByRole('heading', { name: 'Welcome to recruitment', exact: true }).waitFor()
    assert.equal(page.url(), startURL)
    assert.equal(await panel.getByRole('heading', { name: 'Welcome to recruitment', exact: true }).evaluate(el => el === document.activeElement), true)
    await panel.getByRole('button', { name: 'Back', exact: true }).click()
    await waitRead('1')
    await close(); await page.reload({ waitUntil: 'networkidle' }); await open(); await waitRead('1')
    console.log('PASS reading announcement details in place and durable read state after reload')
    const actions = async (id, name) => {
      await panel.locator(`[data-notification-id="durable-${id}"]`).getByRole('button', { name: /^Actions for/ }).click()
      const menu = page.getByRole('menu')
      assert.equal(await menu.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight }), true)
      await menu.getByRole('menuitem', { name, exact: true }).click()
    }
    await actions('1', 'Mark unread')
    await page.waitForFunction(() => document.querySelector('[data-notification-id="durable-1"]')?.dataset.unread === 'true')
    await panel.getByRole('button', { name: 'Unread', exact: true }).click()
    assert.ok(await rows.count() < 50)
    await page.evaluate(() => { window.fixtureFaults.action = true })
    await actions('1', 'Mark read')
    await panel.getByRole('alert').filter({ hasText: 'Couldn’t update' }).waitFor()
    assert.equal(await panel.locator('[data-notification-id="durable-1"]').getAttribute('data-unread'), 'true')
    await page.evaluate(() => { window.fixtureFaults.action = false })
    await panel.getByRole('button', { name: 'Retry', exact: true }).click()
    await panel.locator('[data-notification-id="durable-1"]').waitFor({ state: 'hidden' })
    await page.waitForFunction(() => document.activeElement?.closest('.oc-notification-filter') && document.activeElement.textContent === 'Unread')
    await actions('6', 'Dismiss')
    await panel.locator('[data-notification-id="durable-6"]').waitFor({ state: 'hidden' })
    await panel.getByRole('button', { name: 'All', exact: true }).click()
    await close(); await page.reload({ waitUntil: 'networkidle' }); await open()
    assert.equal(await panel.locator('[data-notification-id="durable-6"]').count(), 0)
    console.log('PASS All/Unread, nested action menus, failure rollback/retry, focus after removal and persistent dismissal')
    await panel.getByRole('button', { name: 'Accept', exact: true }).click()
    await panel.getByRole('region', { name: 'Pending invitations', exact: true }).waitFor({ state: 'hidden' })
    assert.deepEqual(await page.evaluate(() => window.fixtureInvitationActions), ['accept'])
    assert.equal(page.url(), startURL)
    await panel.getByRole('button', { name: 'Mark all updates as read', exact: true }).click()
    await page.waitForFunction(() => window.fixtureBackend.filter(item => !item.archivedAt).every(item => item.readAt))
    assert.ok(await page.evaluate(() => window.fixtureNotificationCalls.some(call => call.action === 'load' && call.cursor)))
    await panel.getByRole('button', { name: 'Unread', exact: true }).click()
    await panel.getByText('You’re all caught up', { exact: true }).waitFor()
    await panel.getByRole('button', { name: 'All', exact: true }).click()
    console.log('PASS existing invitation response controls, all unread pages marked read and unread empty state')
    const scrollFeed = panel.locator('.oc-notification-feed')
    await scrollFeed.evaluate(el => { el.scrollTop = 400 })
    const anchor = await scrollFeed.evaluate(el => { const top = el.getBoundingClientRect().top; const child = Array.from(el.querySelectorAll('[data-notification-id]')).find(child => child.getBoundingClientRect().top >= top); return { id: child.dataset.notificationId, offset: child.getBoundingClientRect().top - top } })
    await page.evaluate(() => { const first = window.fixtureBackend[0]; window.fixtureBackend.unshift({ ...first, id: 'live', title: 'New live update', createdAt: new Date().toISOString(), readAt: null, archivedAt: null }); window.fixtureStreams[0].dispatchEvent(new Event('communications')) })
    await panel.locator('[data-notification-id="durable-live"]').waitFor({ state: 'attached' })
    assert.equal(await bell.getAttribute('aria-expanded'), 'true')
    assert.equal(await page.evaluate(() => window.fixtureStreams.length), 1)
    const afterOffset = await scrollFeed.evaluate((el, id) => el.querySelector(`[data-notification-id="${id}"]`).getBoundingClientRect().top - el.getBoundingClientRect().top, anchor.id)
    assert.ok(Math.abs(afterOffset - anchor.offset) < 3, 'incoming updates preserve the visible feed position')
    assert.match(await bell.getAttribute('aria-label'), /1 unread/)
    await page.evaluate(() => window.fixtureStreams[0].dispatchEvent(new Event('communications')))
    assert.equal(await panel.locator('[data-notification-id="durable-live"]').count(), 1)
    console.log('PASS one realtime subscription, reactive unread/feed updates, deduplication and feed scroll anchoring')
    await scrollFeed.evaluate(el => { el.scrollTop = 0 })
    await panel.getByRole('link', { name: /New application received/ }).click()
    await page.waitForURL('**tool=applicants&applicantId=fixture-app')
    await panel.waitFor({ state: 'hidden' })
    await open(); await panel.getByRole('button', { name: 'Expand notifications', exact: true }).click(); await page.waitForURL('**view=inbox')
    await open(); await panel.getByRole('button', { name: 'View all notifications', exact: true }).click(); await panel.waitFor({ state: 'hidden' })
    console.log('PASS exact record destination and explicit Expand/View all inbox navigation')
    for (const width of [1600, 1440, 1024, 900, 768, 640, 540, 390, 320]) {
      await page.setViewportSize({ width, height: width < 640 ? 844 : 900 }); await open()
      assert.equal(await panel.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight && r.width <= 401 && r.height <= 541 }), true, `popover fits ${width}px`)
      if (width === 390) await page.screenshot({ path: '/tmp/outclass-notification-center-mobile.png' })
      await close()
    }
    await page.setViewportSize({ width: 768, height: 390 }); await open()
    assert.equal(await panel.evaluate(el => el.getBoundingClientRect().bottom <= innerHeight), true)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await panel.evaluate(el => getComputedStyle(el).animationName), 'none')
    await panel.evaluate(el => { window.fixtureReducedAnimations = []; el.addEventListener('animationstart', event => { if (event.target === el) window.fixtureReducedAnimations.push(event.animationName) }) })
    await close(); assert.deepEqual(await page.evaluate(() => window.fixtureReducedAnimations), []); await open()
    await page.keyboard.press('Control+k'); await page.getByRole('dialog', { name: 'Search OutClass', exact: true }).waitFor()
    await panel.waitFor({ state: 'hidden' }); await page.keyboard.press('Escape')
    console.log('PASS desktop/tablet/mobile, short landscape, reduced motion and search shortcut while the popover is open')
    await page.goto(startURL, { waitUntil: 'networkidle' }); await page.evaluate(() => { window.fixtureFaults.load = true; window.dispatchEvent(new Event('outclass:communications-changed')) }); await open()
    await panel.getByRole('alert').filter({ hasText: 'Couldn’t load' }).waitFor()
    await page.evaluate(() => { window.fixtureFaults.load = false }); await panel.getByRole('button', { name: 'Retry', exact: true }).click()
    await panel.getByRole('alert').filter({ hasText: 'Couldn’t load' }).waitFor({ state: 'hidden' })
    await close()
    await page.addInitScript(() => { window.fixtureFaults = { loadDelay: true } })
    await page.reload({ waitUntil: 'networkidle' }); await open()
    await panel.getByRole('status').filter({ hasText: 'Loading notifications' }).waitFor()
    await page.evaluate(() => { window.fixtureFaults.loadDelay = false; window.fixtureReleaseLoad() })
    await rows.first().waitFor()
    await page.evaluate(() => { window.fixtureBackend = []; window.dispatchEvent(new CustomEvent('fixture:counts', { detail: { unread: 0, invitations: 0 } })); window.dispatchEvent(new Event('outclass:communications-changed')) })
    await panel.getByText('You’re all caught up', { exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS initial skeleton, all-empty state, load error/retry, cached feed and no browser errors')
  } finally { await browser?.close(); if (server) await new Promise(resolve => server.close(resolve)); await fs.rm(root, { recursive: true, force: true }) }
}
check().catch(error => { console.error(error); process.exitCode = 1 })
