/** Local-only marketing QA. Samples must never call production mutation APIs. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium, webkit } = require('playwright')
const engine = process.env.OUTCLASS_LANDING_BROWSER === 'webkit' ? webkit : chromium
const baseURL = process.env.OUTCLASS_LANDING_BASE_URL || 'http://127.0.0.1:3000'
if (!['localhost', '127.0.0.1'].includes(new URL(baseURL).hostname)) throw Error('Run landing QA against a local preview only.')
const output = process.env.OUTCLASS_LANDING_QA_DIR || '/tmp/outclass-redesign-qa'
fs.mkdirSync(output, { recursive: true })

async function verify() {
  const browser = await engine.launch({ headless: true, ...(engine === chromium ? { channel: 'chrome' } : {}) })
  const errors = [], mutations = [], results = []
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.method() !== 'GET' && new URL(request.url()).pathname.startsWith('/api/')) mutations.push(request.url()) })
    const overflow = async label => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `horizontal overflow: ${label}`)
    const open = async (audience, hash = 'about') => {
      const response = await page.goto(`${baseURL}/?audience=${audience}#${hash}`, { waitUntil: 'domcontentloaded', timeout: 90000 })
      if (response) assert.equal(response.status(), 200)
      await page.waitForFunction(a => document.querySelector('#product-journey')?.dataset.perspective === a, audience)
      await page.locator('.oc-product-story').first().waitFor({ state: 'visible' })
      await page.waitForFunction(() => document.querySelector('.oc-public-nav')?.dataset.hero === 'false' && document.querySelectorAll('#product-journey').length === 1)
    }
    const frame = scene => page.locator(`[data-scene="${scene}"]:visible`).locator('xpath=ancestor::figure')
    const show = async scene => { const el = frame(scene); await el.evaluate(el => scrollTo({ top: scrollY + el.getBoundingClientRect().top - Math.max(112, (innerHeight - el.getBoundingClientRect().height) / 2), behavior: 'instant' })); await overflow(scene); return el }
    const click = async (el, name) => el.getByRole('button', { name, exact: true }).click()
    const shot = async (scene, width, suffix = '') => {
      const el = await show(scene)
      // Element captures exclude the separate fixed navbar, which is tested below.
      await page.locator('.oc-public-nav').evaluate(el => { el.style.visibility = 'hidden' })
      await el.screenshot({ path: path.join(output, `verified-${width}-${scene}${suffix}.png`) })
      await page.locator('.oc-public-nav').evaluate(el => { el.style.visibility = '' })
    }
    const studentFlow = async width => {
      await open('student')
      let el = await show('discover')
      await click(el, 'Back to clubs')
      await el.getByRole('searchbox', { name: 'Search sample clubs' }).fill('investment')
      assert.equal(await el.locator('.oc-demo-club-list li').count(), 1)
      await click(el, 'View club')
      await el.locator('[data-demo-view="true"]').getByText('Applications open', { exact: true }).waitFor()
      await shot('discover', width)
      await el.getByRole('link', { name: 'Start application', exact: true }).click()
      await page.waitForFunction(() => location.hash === '#journey-2')
      el = await show('apply')
      await click(el, 'Replay application')
      const answer = 'I want to research investment ideas with a team that challenges my assumptions.'
      await el.getByRole('textbox', { name: 'Sample application response' }).fill(answer)
      await click(el, 'Save draft')
      await el.getByText('Draft saved. You can return before submitting.', { exact: true }).waitFor()
      await click(el, 'Review & submit')
      assert.equal(await el.locator('[data-demo-view="true"] blockquote').textContent(), answer)
      await click(el, 'Submit application')
      await el.getByRole('heading', { name: 'Application submitted.', exact: true }).waitFor()
      await shot('apply', width)
      el = await show('student-interview')
      await click(el, 'Try another time')
      await el.getByRole('button', { name: '7:00 PM Room 204', exact: true }).click()
      assert.equal(await el.getByRole('button', { name: '7:00 PM Room 204', exact: true }).getAttribute('aria-pressed'), 'true')
      await click(el, 'Confirm interview')
      await el.getByRole('heading', { name: 'Interview confirmed.', exact: true }).waitFor()
      assert.match(await el.locator('[data-demo-view="true"]').textContent(), /Thursday · 7:00 PM/)
      await shot('student-interview', width)
      el = await show('status')
      await click(el, 'See interview status')
      assert.match(await el.locator('[data-demo-view="true"]').textContent(), /Thursday · 7:00 PM/)
      await click(el, 'Preview decision update')
      await el.getByText('Ready for your response', { exact: true }).waitFor()
      await shot('status', width)
      el = await show('join')
      await click(el, 'Replay offer example')
      await el.getByText('Awaiting your response', { exact: true }).waitFor()
      await click(el, 'Accept offer')
      await el.getByText('Offer accepted. Welcome to JIS.', { exact: true }).waitFor()
      await click(el, 'Open member workspace')
      await el.getByText('MEMBER WORKSPACE', { exact: true }).waitFor()
      await shot('join', width)
      await overflow(`student ${width}`)
      results.push({ audience: 'student', width, stages: 5, interactions: 'search, profile, draft, review, submission, booking, decision, offer, membership' })
      console.log(`PASS student journey and sample context at ${width}px`)
    }
    const leaderFlow = async width => {
      await open('leader')
      let el = await show('build')
      await click(el, 'Club profile')
      await el.getByText('Sample club claim approved. Pending claims do not grant access.', { exact: true }).waitFor()
      await click(el, 'Open recruitment setup')
      await el.getByRole('textbox', { name: 'Sample application question' }).fill('What research question would you explore with us?')
      await click(el, 'Save setup')
      await shot('build', width)
      el = await show('recruit')
      await click(el, 'Application')
      await el.getByRole('heading', { name: 'What research question would you explore with us?', exact: true }).waitFor()
      await click(el, 'Open applicant pipeline')
      await click(el, 'Select Jordan Avery')
      await el.getByText('Jordan Avery selected · Application review', { exact: true }).waitFor()
      await shot('recruit', width)
      el = await show('review')
      await click(el, 'Application')
      await el.getByRole('checkbox', { name: 'Show an anonymous-round example' }).check()
      await el.getByRole('heading', { name: 'Applicant 014', exact: true }).waitFor()
      assert.equal(await el.getByRole('heading', { name: 'Jordan Avery', exact: true }).count(), 0)
      await el.getByRole('checkbox', { name: 'Show an anonymous-round example' }).uncheck()
      await click(el, 'Evaluate application')
      await el.getByRole('combobox', { name: 'Sample Motivation & fit score' }).selectOption('5')
      await el.getByRole('textbox', { name: 'Sample reviewer note' }).fill('Thoughtful evidence and a clear point of view.')
      await click(el, 'Save evaluation')
      await shot('review', width)
      el = await show('leader-interview')
      await click(el, 'Replay panel example')
      await el.getByText('INTERVIEWER AVAILABILITY', { exact: true }).waitFor()
      await click(el, 'Review rooms')
      await el.getByText('2 per session', { exact: true }).waitFor()
      await click(el, 'Auto-Fill Panels')
      await el.getByText('This is a proposal. Assignments are not official until owner approval.', { exact: true }).waitFor()
      await shot('leader-interview', width, '-draft')
      await click(el, 'Review & Publish')
      await el.getByText('FINAL PANEL APPROVAL', { exact: true }).waitFor()
      assert.equal(await el.getByText('Published', { exact: true }).count(), 0)
      await click(el, 'Return to editing')
      await click(el, 'Review & Publish')
      await click(el, 'Confirm & Publish Panels')
      await el.getByText('Owner confirmed and published this schedule.', { exact: true }).waitFor()
      await shot('leader-interview', width)
      el = await show('decide')
      await click(el, 'Try another decision')
      await click(el, 'Waitlist')
      await click(el, 'Record decision')
      await el.getByText('Waitlisted', { exact: true }).waitFor()
      await el.getByText('No membership offer', { exact: true }).waitFor()
      await click(el, 'Try another decision')
      await click(el, 'Accept')
      await click(el, 'Record decision')
      await el.getByText('Pending student response', { exact: true }).waitFor()
      await shot('decide', width)
      el = await show('manage')
      await click(el, 'Members')
      await el.getByText('Jordan accepted the membership offer', { exact: true }).waitFor()
      await click(el, 'View member access')
      await el.getByRole('combobox', { name: 'Sample member title' }).selectOption('Project lead')
      await el.getByRole('checkbox', { name: 'Review applications', exact: true }).check()
      await click(el, 'Save member access')
      await click(el, 'Publish announcement')
      await click(el, 'Review sample submission')
      await el.getByText(/Jordan’s submission/).waitFor()
      await shot('manage', width)
      await overflow(`leader ${width}`)
      results.push({ audience: 'leader', width, stages: 6, interactions: 'setup, rounds, pipeline, anonymous review, rubric, availability, rooms, draft, approval, publication, decisions, roster, access, announcements, submissions' })
      console.log(`PASS leader journey and explicit panel approval at ${width}px`)
    }
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 })
      await studentFlow(width)
      await leaderFlow(width)
    }
    for (const size of [{ width: 320, height: 844 }, { width: 540, height: 844 }, { width: 768, height: 1024 }, { width: 1024, height: 768 }, { width: 844, height: 390 }]) {
      await page.setViewportSize(size)
      for (const audience of ['student', 'leader']) {
        await open(audience)
        assert.equal(await page.locator('.oc-product-story').count(), audience === 'student' ? 5 : 6)
        for (const chapter of await page.locator('.oc-product-story').all()) {
          await chapter.scrollIntoViewIfNeeded()
          await overflow(`${audience} ${size.width} ${await chapter.getAttribute('data-stage')}`)
          assert.equal(await chapter.locator('button, input, textarea, select').evaluateAll(els => els.filter(el => !el.closest('[inert]')).every(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth + 1 })), true)
        }
        await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
        await page.waitForFunction(() => !document.querySelector('.oc-public-nav').dataset.journey)
        await page.locator('.oc-campus-photo').evaluate(el => el.decode())
        await page.screenshot({ path: path.join(output, `verified-${size.width}-${audience}-full.png`), fullPage: true })
      }
      console.log(`PASS both complete journeys at ${size.width}×${size.height}`)
    }
    // Semantic audience handoff must retain Interview despite differing chapter counts.
    await page.setViewportSize({ width: 1440, height: 1000 })
    await open('student', 'journey-3')
    await page.waitForFunction(() => document.querySelector('.oc-public-nav').dataset.journey === 'true')
    const compact = page.locator('.oc-public-journey-desktop')
    const line = 260
    const reading = () => page.evaluate(line => [...document.querySelectorAll('.oc-product-story')].find(el => { const r = el.getBoundingClientRect(); return r.top <= line && r.bottom > line })?.dataset.stage, line)
    const navBounds = () => page.locator('.oc-public-nav-row').boundingBox()
    const initialNav = await navBounds()
    assert.equal(await reading(), 'interview')
    await click(compact, 'Club Leaders')
    await page.waitForFunction(() => document.querySelector('#product-journey').dataset.perspective === 'leader')
    await page.waitForTimeout(700)
    assert.equal(await reading(), 'interview')
    assert.deepEqual(await navBounds(), initialNav)
    assert.equal(await page.locator('.oc-journey-controls [data-perspective-option="leader"]').getAttribute('aria-pressed'), 'true')
    await click(compact, 'Students')
    await page.waitForFunction(() => document.querySelector('#product-journey').dataset.perspective === 'student')
    await page.waitForTimeout(700)
    assert.equal(await reading(), 'interview')
    let example = await show('student-interview')
    await click(example, 'Try another time')
    await example.getByRole('button', { name: '7:00 PM Room 204', exact: true }).click()
    await click(example, 'Confirm interview')
    await click(compact, 'Club Leaders')
    await page.waitForFunction(() => document.querySelector('#product-journey').dataset.perspective === 'leader')
    example = await show('leader-interview')
    assert.match(await example.locator('[data-demo-view="true"]').textContent(), /Jordan Avery · Thursday · 7:00 PM/)
    await click(compact, 'Students')
    await page.waitForFunction(() => document.querySelector('#product-journey').dataset.perspective === 'student')
    await page.screenshot({ path: path.join(output, 'verified-interview-toggle.png') })
    console.log('PASS equivalent chapter switching, synchronized controls, and stable floating navigation')
    await open('leader', 'journey-6')
    await page.waitForFunction(() => document.querySelector('[data-stage="manage"]').getBoundingClientRect().top >= 0 && document.querySelector('[data-stage="manage"]').getBoundingClientRect().top < 200)
    assert.equal(await reading(), 'manage')
    await click(compact, 'Students')
    await page.waitForFunction(() => document.querySelector('#product-journey').dataset.perspective === 'student')
    assert.equal(await reading(), 'belong')
    for (const hash of ['students', 'club-leaders', 'clubs']) {
      const response = await page.goto(`${baseURL}/#${hash}`, { waitUntil: 'domcontentloaded', timeout: 90000 })
      if (response) assert.equal(response.status(), 200)
      await page.waitForFunction(a => document.querySelector('#product-journey')?.dataset.perspective === a, hash === 'students' ? 'student' : 'leader')
    }
    // Fixed account and school routes are read-only checks; never submit a real form.
    for (const [name, href] of [['Get Started', '/signup'], ['Log In', '/login'], ['Request Your School', '/request-school']]) assert.equal(await page.locator('.oc-public-nav').getByRole('link', { name, exact: true }).first().getAttribute('href'), href)
    for (const route of ['/signup', '/login', '/request-school', '/about', '/uva']) assert.equal((await page.request.get(`${baseURL}${route}`)).status(), 200)
    // Mobile controls and keyboard activation work with the same shared state.
    await page.setViewportSize({ width: 390, height: 844 })
    await open('student', 'journey-3')
    await page.waitForFunction(() => document.querySelector('.oc-public-nav').dataset.journey === 'true')
    const menu = page.getByRole('button', { name: 'Open navigation menu and perspective switcher', exact: true })
    await menu.focus(); await page.keyboard.press('Enter')
    const mobile = page.locator('.oc-public-journey-mobile')
    await mobile.getByRole('button', { name: 'Club Leaders', exact: true }).focus(); await page.keyboard.press('Space')
    await page.waitForFunction(() => document.querySelector('#product-journey').dataset.perspective === 'leader')
    assert.equal(await mobile.locator('[data-perspective-option="leader"]').getAttribute('aria-pressed'), 'true')
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('button', { name: 'Open navigation menu and perspective switcher' }).evaluate(el => el === document.activeElement), true)
    assert.equal(await page.locator('.oc-perspective-indicator').first().evaluate(el => getComputedStyle(el).transitionDuration), '0s')
    console.log('PASS direct/legacy chapter links, existing routes, mobile keyboard, and reduced motion')
    // Observe finite playback in normal motion, then pause, replay, and reverse-scroll.
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    for (const audience of ['student', 'leader']) {
      await open(audience)
      for (const scene of audience === 'student' ? ['discover', 'apply', 'student-interview', 'status', 'join'] : ['build', 'recruit', 'review', 'leader-interview', 'decide', 'manage']) {
        const el = await show(scene)
        await el.getByRole('button', { name: 'Replay example', exact: true }).waitFor({ timeout: 12000 })
        await el.getByRole('button', { name: 'Replay example', exact: true }).click()
        await click(el, 'Pause example')
        assert.equal(await el.locator('xpath=..').getAttribute('data-demo-paused'), 'true')
        await click(el, 'Resume example')
        await el.getByRole('button', { name: 'Replay example', exact: true }).waitFor({ timeout: 12000 })
      }
      // Large jumps and reversing direction keep navigation and completed demos stable.
      for (const y of [0, 3000, 1800, 6000, 0]) await page.evaluate(y => scrollTo({ top: y, behavior: 'instant' }), y)
      await page.locator('#about').scrollIntoViewIfNeeded()
      await overflow(`normal motion ${audience}`)
      console.log(`PASS finite visible playback, pause/replay, and reverse/fast scrolling for ${audience}`)
    }
    assert.deepEqual(errors, [])
    assert.deepEqual(mutations, [])
    fs.writeFileSync(path.join(output, 'journey-verification.json'), JSON.stringify({ results, errors, mutations }, null, 2))
    console.log('PASS no browser errors and no marketing mutation requests')
  } finally { await browser.close() }
}
verify().catch(error => { console.error(error); process.exitCode = 1 })
