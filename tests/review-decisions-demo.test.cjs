// Demo Mode parity for staged decisions and grading categories: nothing reaches the applicant until Send.
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { harness } = require('./helpers/demo-harness.cjs')

test('Demo: staged decisions change nothing until sent, can be undone, and send through the decision publisher', async () => {
  const h = harness(), { demoStore } = h.load('lib/demo/store.ts'), api = h.load('lib/workspace-api.ts')
  demoStore.start()
  const club = demoStore.get().clubs[0]
  demoStore.mutate(s => { s.perspective = { role: 'leader', clubId: club.id } })
  const pipeline = await api.getClubPipeline(club.id)
  assert.ok(pipeline.rubric.categories.length >= 1)
  const app = pipeline.applications.find(a => ['SUBMITTED', 'IN_REVIEW', 'INTERVIEWING'].includes(a.status) && !a.studentId.startsWith('anonymous-') && a.studentId !== demoStore.get().students[0].id)
  assert.ok(app)
  const view = await api.stageDecision({ clubId: club.id, applicationId: app.id, outcome: 'REJECT', expectedStatus: app.status, expectedRoundId: app.roundId })
  assert.equal(view.targetStatus, 'REJECTED')
  assert.equal(demoStore.get().applications.find(a => a.id === app.id).status, app.status, 'staging publishes nothing')
  assert.equal((await api.listStagedDecisions(club.id)).length, 1)
  await assert.rejects(api.stageDecision({ clubId: club.id, applicationId: app.id, outcome: 'REJECT', expectedStatus: 'SUBMITTED', expectedRoundId: app.roundId }), /changed/)
  await api.clearStagedDecision({ clubId: club.id, applicationId: app.id })
  assert.equal((await api.listStagedDecisions(club.id)).length, 0, 'Undo removes it')
  await api.stageDecision({ clubId: club.id, applicationId: app.id, outcome: 'REJECT', expectedStatus: app.status, expectedRoundId: app.roundId })
  const result = await api.sendStagedDecisions({ clubId: club.id, applicationIds: [app.id], confirmed: true })
  assert.deepEqual(result, { sent: 1, stale: [] })
  assert.equal(demoStore.get().applications.find(a => a.id === app.id).status, 'REJECTED')
  assert.equal((await api.listStagedDecisions(club.id)).length, 0)
  const saved = await api.saveReviewRubric({ clubId: club.id, rubric: { categories: [] } })
  assert.deepEqual(saved.rubric.categories, [])
  assert.deepEqual((await api.getClubPipeline(club.id)).rubric.categories, [], 'no categories: decisions only')
})
