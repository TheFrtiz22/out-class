const { test } = require('node:test'), assert = require('node:assert/strict'), path = require('node:path'), { spawn } = require('node:child_process'), { chromium } = require('playwright')

test('interview composer Enter actions, multiline, validation, duplicate guards, failure retry and review isolation in Chromium', async () => {
  const server = spawn(process.execPath, [path.join(__dirname, 'helpers/interview-browser-fixture.cjs')], { cwd: path.join(__dirname, '..'), env: { ...process.env, OUTCLASS_INTERACTION_BASELINE: 'HEAD' }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  let output = ''; server.stdout.on('data', b => { output += b }); server.stderr.on('data', b => { output += b })
  const ready = new Promise((resolve, reject) => { server.stdout.on('data', () => { if (output.includes('fixture ready:')) resolve() }); server.on('exit', code => reject(Error('Fixture exited ' + code + ': ' + output))); })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    await ready
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const external = [], errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.route('**/*', r => { if (/^(http:\/\/127\.0\.0\.1:4318\/|blob:)/.test(r.request().url())) return r.continue(); external.push(r.request().url()); return r.abort() })
    await page.goto('http://127.0.0.1:4318/?mode=after&latency=300')
    await page.getByRole('region', { name: 'Available questions' }).getByRole('button').first().click()
    const notes = page.getByRole('textbox', { name: 'Your private notes', exact: true })
    await notes.fill('Before modified shortcut');
    await notes.press('Control+Enter');await notes.press('Meta+Enter');await notes.evaluate(el=>el.form.requestSubmit());await page.waitForFunction(()=>document.querySelector('#interview-evaluation')?.getAttribute('data-saving')==='false');
    assert.equal(await page.getByRole('heading',{name:'Post-interview',exact:true}).count(),0);
    assert.equal(await notes.inputValue(),'Before modified shortcut');
    await notes.fill('First line'); await notes.press('Shift+Enter'); await page.keyboard.type('Second line')
    assert.equal(await notes.inputValue(), 'First line\nSecond line')
    await notes.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
    assert.equal(await notes.isVisible(), true)
    await page.getByText(/Isolated browser fixture/).click()
    await page.getByRole('button', { name: 'Toggle synthetic request failure', exact: true }).click()
    await notes.press('Enter')
    await page.getByRole('alert').filter({ hasText: 'Your interview could not be saved' }).waitFor()
    assert.equal(await notes.inputValue(), 'First line\nSecond line')
    await page.getByRole('button', { name: 'Toggle synthetic request failure', exact: true }).click()
    await notes.press('Enter')
    await page.keyboard.press('Enter') // held/repeated or immediate second key cannot create another completion
    await notes.waitFor({ state: 'hidden' })
    assert.equal(await page.getByRole('button', { name: 'Question bank', exact: true }).evaluate(el => el === document.activeElement), true)
    assert.equal(await page.getByRole('complementary', { name: 'Your notes and completed questions' }).getByRole('listitem').count(), 1)
    await page.getByRole('button', { name: '+ Off-script question', exact: true }).click()
    const question = page.getByRole('textbox', { name: 'Off-script question', exact: true })
    await question.press('Enter'); await page.getByText('Enter an off-script question before adding it.', { exact: false }).waitFor()
    await question.fill('A synthetic off-script question'); await question.press('Shift+Enter'); await page.keyboard.type('with another line')
    await question.press('Enter'); await notes.waitFor()
    assert.equal(await question.count(), 0)
    assert.equal(await notes.evaluate(el => el === document.activeElement), true)
    await notes.fill('Off-script answer'); await notes.press('Enter'); await notes.waitFor({ state: 'hidden' })
    const misc = page.getByRole('textbox', { name: 'Miscellaneous notes', exact: true })
    await misc.fill('Discuss'); await misc.press('Enter'); await page.keyboard.type('Later')
    assert.equal(await misc.inputValue(), 'Discuss\nLater')
    assert.equal(await page.getByRole('region', { name: 'Submitted review', exact: true }).count(), 0)

    await page.getByRole('button', { name: 'Open résumé for Fictional Applicant one', exact: true }).click()
    const layer = page.getByRole('document', { name: 'Selectable résumé text' }), span = layer.locator('span').first()
    await span.waitFor(); const b = await span.boundingBox()
    await page.mouse.move(b.x + 2, b.y + b.height / 2); await page.mouse.down(); await page.mouse.move(b.x + b.width - 2, b.y + b.height / 2, { steps: 8 }); await page.mouse.up()
    const quote = await page.evaluate(() => getSelection().toString()); assert.ok(quote.trim())
    await page.keyboard.type('Highlighted text: continuous sentence!', { delay: 0 })
    const comment = page.getByRole('textbox', { name: 'Highlight comment', exact: true })
    assert.equal(await comment.inputValue(), 'Highlighted text: continuous sentence!')
    await comment.press('Shift+Enter'); await page.keyboard.type('Second line')
    await comment.press('Enter'); await page.keyboard.press('Enter'); await comment.waitFor({ state: 'hidden' })
    const row = page.getByRole('complementary', { name: 'Shared résumé comments' }).getByRole('listitem').filter({ hasText: 'Highlighted text: continuous sentence!' })
    await row.waitFor(); assert.equal(await row.count(), 1); assert.ok((await row.innerText()).includes(quote))
    assert.equal(await row.evaluate(el => el === document.activeElement), true)
    await page.getByRole('button', { name: 'Add general résumé note', exact: true }).click()
    const general = page.getByRole('textbox', { name: 'General résumé note', exact: true })
    await general.press('Enter'); await page.getByText('Enter a comment of 1–10,000 characters.', { exact: true }).waitFor()
    await general.fill('Retained general note')
    await page.getByRole('button', { name: 'Close résumé', exact: true }).click()
    await page.getByRole('button', { name: 'Toggle synthetic request failure', exact: true }).click()
    await page.getByRole('button', { name: 'Open résumé for Fictional Applicant one', exact: true }).click()
    await page.getByRole('button', { name: 'Add general résumé note', exact: true }).click(); await general.fill('Retry general note'); await general.press('Enter')
    await page.getByText(/Comment was not saved/).waitFor(); assert.equal(await general.inputValue(), 'Retry general note')
    await page.getByRole('button', { name: 'Save comment', exact: true }).waitFor()
    // Test-only failure control is outside the modal; no application access rule is bypassed.
    await page.locator('button').filter({ hasText: /^Toggle synthetic request failure$/ }).evaluate(el => el.click())
    await general.press('Enter'); await general.waitFor({ state: 'hidden' })
    await page.getByRole('listitem').filter({ hasText: 'Retry general note' }).waitFor()
    assert.equal(await page.getByRole('listitem').filter({ hasText: 'Retry general note' }).count(), 1)
    await page.setViewportSize({ width: 390, height: 900 })
    await page.getByRole('button', { name: 'Add general résumé note', exact: true }).click()
    await general.fill('Mobile comment'); await general.press('Shift+Enter'); await page.keyboard.type('second line'); await general.press('Enter'); await general.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Close résumé', exact: true }).click()
    await page.getByRole('button', { name: 'End current interview', exact: true }).click()
    const applicantQuestions = page.getByRole('textbox', { name: 'Questions the applicant asked', exact: true })
    await applicantQuestions.fill('Discussion'); await applicantQuestions.press('Enter'); await page.keyboard.type('Continues')
    assert.equal(await applicantQuestions.inputValue(), 'Discussion\nContinues')
    assert.equal(await page.getByRole('region', { name: 'Submitted review', exact: true }).count(), 0)
    assert.equal(await page.getByRole('slider', { name: 'Overall score' }).getAttribute('aria-valuetext'), 'Not scored; interact to select a score')
    assert.deepEqual(external, []); assert.deepEqual(errors, [])
    console.log('Actual PDF selection → continuous typing → Enter, multiline, validation, save failure, focus, completion and review isolation passed.')
  } finally { await browser.close(); server.kill() }
})
